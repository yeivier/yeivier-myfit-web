	<h3>5. Responsabilidad del usuario</h3>
	<p>Reconoces y aceptas que eres el único y total responsable de:</p>
	<ul>
		<li>Tu propia salud y seguridad durante el ejercicio</li>
		<li>Usar una forma y técnica de ejercicio adecuadas</li>
		<li>Usar el equipo apropiado y asegurarte de que esté en buen estado de funcionamiento</li>
		<li>Ejercitarte en un entorno seguro</li>
		<li>Comenzar con pesos y niveles de intensidad apropiados para tu nivel de condición física</li>
		<li>Calentar adecuadamente antes del ejercicio</li>
		<li>Enfriar y estirar después del ejercicio</li>
		<li>Mantenerte correctamente hidratado y nutrido</li>
		<li>Obtener descanso y recuperación adecuados</li>
		<li>Ajustar o modificar cualquier recomendación según tus capacidades y limitaciones individuales</li>
		<li>Escuchar a tu cuerpo y detenerte de inmediato si experimentas dolor, molestias o síntomas inusuales</li>
		<li>Buscar atención médica profesional cuando sea necesario</li>
		<li>Informar a entrenadores, instructores o compañeros de entrenamiento sobre cualquier condición médica o
			lesión</li>
	</ul>

	<h3>6. Descargo de responsabilidad del algoritmo de progresión</h3>
	<p>
		Nuestros algoritmos de progresión se basan en principios generales de acondicionamiento físico, investigación en
		ciencias del ejercicio y modelos matemáticos. <strong>
			NO constituyen asesoramiento médico personalizado y NO están adaptados a tu fisiología específica, historial
			médico, nivel de condición física actual, historial de lesiones, biomecánica ni circunstancias individuales.
		</strong>
	</p>
	<p>Los algoritmos:</p>
	<ul>
		<li>No pueden tener en cuenta tus limitaciones o condiciones físicas particulares</li>
		<li>No pueden predecir cómo responderá tu cuerpo al entrenamiento</li>
		<li>Pueden sugerir progresiones demasiado agresivas o demasiado conservadoras para ti</li>
		<li>No consideran factores como la calidad del sueño, los niveles de estrés, la nutrición o la capacidad de
			recuperación</li>
		<li>No están supervisados por profesionales médicos o de la condición física</li>
	</ul>
	<p>
		<strong>
			Debes usar tu propio criterio, sentido común y orientación profesional para modificar las recomendaciones
			según corresponda a tus circunstancias individuales.
		</strong> Si algo se siente mal o demasiado difícil, no lo hagas.
	</p>

