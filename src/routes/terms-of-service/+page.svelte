		La información proporcionada por MyFit ("nosotros" o "nuestro") en myfit.fit (el "Sitio") y nuestra aplicación
		móvil tiene fines meramente informativos generales. Toda la información en el Sitio y en nuestra aplicación
		móvil se proporciona de buena fe; sin embargo, no ofrecemos ninguna declaración ni garantía de ningún tipo,
