		cualquier información en el Sitio o en nuestra aplicación móvil.
	</p>
	<p>
		<strong>
			El Servicio no pretende sustituir el asesoramiento médico profesional, el diagnóstico ni el tratamiento.
		</strong>
	</p>

	<h3>2. Consulta a tu médico</h3>
	<p>
		<strong>
			Antes de comenzar cualquier programa de ejercicio, debes consultar con tu médico u otro profesional de la
			salud calificado.
		</strong> Esto es especialmente importante si:
	</p>
	<ul>
		<li>Tienes alguna condición de salud preexistente</li>
		<li>Tienes antecedentes de enfermedad cardíaca, presión arterial alta u otras afecciones cardiovasculares</li>
		<li>Experimentas dolor en el pecho, mareos o dificultad para respirar durante la actividad física</li>
		<li>Tienes problemas articulares, lesiones o limitaciones físicas</li>
		<li>Estás embarazada o en posparto</li>
		<li>Estás tomando algún medicamento que pueda afectar tu capacidad para hacer ejercicio</li>
		<li>Tienes cualquier otro problema de salud</li>
	</ul>
	<p>
		Nunca ignores el consejo médico profesional ni retrases su búsqueda debido a algo que hayas leído o consultado a
		través del Servicio.
	</p>

	<h3>3. Asunción de riesgo</h3>
	<p>
		Reconoces y aceptas que el ejercicio físico conlleva riesgos inherentes de lesión, enfermedad o incluso muerte.
		Al usar los algoritmos de progresión, las recomendaciones de entrenamiento y las funciones de entrenamiento de
		MyFit, asumes voluntaria y conscientemente todos los riesgos asociados con dicho ejercicio, previstos o
		imprevistos, incluidos entre otros:
	</p>
	<ul>
		<li>Distensiones, esguinces y desgarros musculares</li>
		<li>Lesiones de tendones y ligamentos</li>
		<li>Lesiones y daños articulares</li>
		<li>Fracturas óseas y fracturas por estrés</li>
		<li>Eventos cardiovasculares, incluidos infarto y accidente cerebrovascular</li>
		<li>Agotamiento por calor e insolación</li>
		<li>Deshidratación</li>
		<li>Desmayos y mareos</li>
		<li>Rabdomiólisis (degradación del tejido muscular)</li>
		<li>Otras lesiones agudas o crónicas</li>
		<li>Agravamiento de condiciones preexistentes</li>
		<li>En casos poco frecuentes, la muerte</li>
	</ul>
	<p>
		<strong>
			Aceptas expresamente que el uso del Servicio y cualquier ejercicio realizado con base en información del
			Servicio es bajo tu propio riesgo.
		</strong>
	</p>

